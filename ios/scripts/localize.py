#!/usr/bin/env python3
"""Builds the app's .strings and .stringsdict files from ios/Localization/<lang>.json.

Usage: ios/scripts/localize.py            write the files
       ios/scripts/localize.py --check    fail if a language is incomplete or the files are stale

Each JSON file maps an English key to its translation. A plural key maps to an object:
  {"format": "%#@n@ · %@", "one": "%lld item", "other": "%lld items"}
"format" is optional (default "%#@n@"); the categories follow CLDR for the language.
The key "_InfoPlist" holds Info.plist strings, written to the app target only.
"""
import json, os, plistlib, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
IOS = os.path.join(HERE, "..")
SRC = os.path.join(IOS, "Localization")
SHARED_OUT = os.path.join(IOS, "Shared", "Localization")
APP_OUT = os.path.join(IOS, "Dawnwell", "Resources")

LANGS = ["en", "de", "fr", "es", "it", "pt-BR", "pt-PT", "nl", "sv", "da", "nb", "fi",
         "pl", "tr", "ja", "ko", "zh-Hans", "zh-Hant"]

PLURALS = {
    "en": ["one", "other"], "de": ["one", "other"], "es": ["one", "other"], "it": ["one", "other"],
    "pt-BR": ["one", "other"], "pt-PT": ["one", "other"], "nl": ["one", "other"], "sv": ["one", "other"],
    "da": ["one", "other"], "nb": ["one", "other"], "fi": ["one", "other"], "tr": ["one", "other"],
    "fr": ["one", "other"], "pl": ["one", "few", "many", "other"],
    "ja": ["other"], "ko": ["other"], "zh-Hans": ["other"], "zh-Hant": ["other"],
}

SPEC = re.compile(r"%(?:\d+\$)?(?:lld|ld|d|@|lf|f)|%#@\w+@")


def specs(s):
    """Format specifiers in order of argument, with positions taken off."""
    found = [(m.group(0)) for m in SPEC.finditer(s.replace("%%", ""))]
    positional = [re.match(r"%(\d+)\$(.*)", f) for f in found]
    if all(positional) and positional:
        return ["%" + p.group(2) for p in sorted(positional, key=lambda p: int(p.group(1)))]
    return [re.sub(r"^%\d+\$", "%", f) for f in found]


def load(lang):
    with open(os.path.join(SRC, f"{lang}.json"), encoding="utf-8") as f:
        return json.load(f)


def flat_specs(value):
    """The arguments a value takes: plural forms are put back into their format."""
    if isinstance(value, str):
        return specs(value)
    fmt = value.get("format", "%#@n@")
    out = []
    for s in specs(fmt):
        out += specs(value["other"]) if s.startswith("%#@") else [s]
    return out


def problems():
    en = load("en")
    out = []
    for lang in LANGS:
        data = load(lang)
        for key, value in en.items():
            if key == "_InfoPlist":
                continue
            if key not in data:
                out.append(f"{lang}: missing {key!r}")
                continue
            tr = data[key]
            if isinstance(value, dict) != isinstance(tr, dict):
                out.append(f"{lang}: {key!r} must {'be' if isinstance(value, dict) else 'not be'} plural")
                continue
            if isinstance(tr, dict):
                need = PLURALS[lang]
                missing = [c for c in need if c not in tr]
                if missing:
                    out.append(f"{lang}: {key!r} lacks plural forms {missing}")
                for c in need:
                    if c in tr and specs(tr[c]) != specs(value["other"]):
                        out.append(f"{lang}: {key!r} [{c}] has {specs(tr[c])}, English has {specs(value['other'])}")
                fmt_en, fmt_tr = value.get("format", "%#@n@"), tr.get("format", "%#@n@")
                if specs(fmt_tr) != specs(fmt_en):
                    out.append(f"{lang}: {key!r} format has {specs(fmt_tr)}, English has {specs(fmt_en)}")
            elif sorted(specs(tr)) != sorted(specs(value)) or (specs(tr) != specs(value) and not re.search(r"%\d+\$", tr)):
                out.append(f"{lang}: {key!r} has {specs(tr)}, key has {specs(value)}")
            if isinstance(value, str) and specs(key) != specs(value):
                out.append(f"en: {key!r} value does not match its key")
        for key in data:
            if key not in en:
                out.append(f"{lang}: extra key {key!r}")
        if set(en.get("_InfoPlist", {})) != set(data.get("_InfoPlist", {})):
            out.append(f"{lang}: Info.plist strings differ from English")
    return out


def escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def strings_file(entries):
    lines = ["/* Generated by ios/scripts/localize.py from ios/Localization. Do not edit. */", ""]
    for k, v in entries:
        lines.append(f'"{escape(k)}" = "{escape(v)}";')
    return "\n".join(lines) + "\n"


def stringsdict(entries, lang):
    root = {}
    for k, v in entries:
        rule = {"NSStringFormatSpecTypeKey": "NSStringPluralRuleType", "NSStringFormatValueTypeKey": "lld"}
        for c in PLURALS[lang] + ["other"]:
            rule[c] = v[c]
        if lang == "fr":
            rule["many"] = v["other"]
        root[k] = {"NSStringLocalizedFormatKey": v.get("format", "%#@n@"), "n": rule}
    return plistlib.dumps(root, fmt=plistlib.FMT_XML, sort_keys=True)


def outputs():
    files = {}
    for lang in LANGS:
        data = load(lang)
        plain = [(k, v) for k, v in data.items() if isinstance(v, str)]
        plural = [(k, v) for k, v in data.items() if isinstance(v, dict) and k != "_InfoPlist"]
        d = os.path.join(SHARED_OUT, f"{lang}.lproj")
        files[os.path.join(d, "Localizable.strings")] = strings_file(plain).encode("utf-8")
        files[os.path.join(d, "Localizable.stringsdict")] = stringsdict(plural, lang)
        info = sorted(data.get("_InfoPlist", {}).items())
        files[os.path.join(APP_OUT, f"{lang}.lproj", "InfoPlist.strings")] = strings_file(info).encode("utf-8")
    return files


def read_strings_keys(lang):
    """Keys of a language, as the app will look them up."""
    return {k for k in load(lang) if k != "_InfoPlist"}


def main():
    errs = problems()
    if errs:
        print("\n".join(errs))
        sys.exit(1)
    stale = []
    for path, content in outputs().items():
        old = open(path, "rb").read() if os.path.exists(path) else None
        if old != content:
            if "--check" in sys.argv:
                stale.append(os.path.relpath(path, IOS))
            else:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "wb") as f:
                    f.write(content)
    if stale:
        print("Out of date, run ios/scripts/localize.py:\n  " + "\n  ".join(stale))
        sys.exit(1)
    print(f"{len(LANGS)} languages OK")


if __name__ == "__main__":
    main()
